/* CloudLens AutoPilot for AWS — landing site behaviors */
(function () {
  'use strict';

  // ----- THEME -----
  // Default to light mode on first visit. If the user explicitly toggles to
  // dark, that preference is saved to localStorage and respected on return.
  var root = document.documentElement;
  var stored = localStorage.getItem('cl-theme');
  var theme = stored || 'light';
  root.setAttribute('data-theme', theme);

  var toggle = document.getElementById('theme-toggle');
  if (toggle) {
    toggle.addEventListener('click', function () {
      var next = root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
      root.setAttribute('data-theme', next);
      localStorage.setItem('cl-theme', next);
    });
  }

  // ----- WIZARD: live terraform.tfvars preview -----
  // The form fields are re-used from the original ansible-azure template but
  // semantically remapped for AutoPilot AWS Terraform variables:
  //   clms-ip       -> CLMS public IP (for Phase 2 manual configuration ref)
  //   project-key   -> CLMS project key (Phase 2 ref)
  //   tags          -> resource tags
  //   rgs           -> allowed CIDR list (comma-separated)
  //   mode          -> deployment mode: "greenfield" or "existing-vpc"
  var clmsIp = document.getElementById('clms-ip');
  var projKey = document.getElementById('project-key');
  var tags = document.getElementById('tags');
  var rgs = document.getElementById('rgs');
  var mode = document.getElementById('mode');
  var tfvarsOut = document.getElementById('yaml-preview'); // kept ID for CSS continuity

  function quote(s) { return '"' + String(s).replace(/"/g, '\\"') + '"'; }

  function buildTfvars() {
    var clmsIpVal = (clmsIp && clmsIp.value ? clmsIp.value.trim() : '') || '10.0.0.10';
    var projKeyVal = (projKey && projKey.value ? projKey.value.trim() : '') || 'paste-from-clms-projects-api-keys';
    var tagsValue = (tags && tags.value ? tags.value.trim() : '') || 'Env=AWS,Customer=Acme';
    var cidrList = (rgs && rgs.value ? rgs.value.split(',').map(function (s) { return s.trim(); }).filter(Boolean) : []);
    if (!cidrList.length) cidrList = ['us-east-1'];
    var modeVal = (mode && mode.value) || 'ssm';

    var lines = [];
    lines.push('# customer_input.yaml');
    lines.push('# Generated by keysight-tech.github.io/cloudlens-ansible-aws');
    lines.push('# Place in the repo root and run:  bash quickstart.sh');
    lines.push('');
    lines.push('aws:');
    lines.push('  profile: "default"');
    lines.push('  regions:');
    cidrList.forEach(function (r) { lines.push('    - "' + r + '"'); });
    lines.push('  tag_filters:');
    lines.push('    cloudlens: "yes"');
    lines.push('    env: "prod"');
    lines.push('  windows_connection: "' + modeVal + '"   # ssm | winrm');
    lines.push('  linux_connection:   "ssh"');
    lines.push('  ssh_key_path:    "~/.aws/your-key.pem"');
    lines.push('  ssh_user_ubuntu: "ubuntu"');
    lines.push('  ssh_user_rhel:   "ec2-user"');
    lines.push('');
    lines.push('cloudlens:');
    lines.push('  manager_ip_or_fqdn: "' + clmsIpVal + '"');
    lines.push('  project_key:        "' + projKeyVal + '"');
    lines.push('  custom_tags:        "' + tagsValue + '"');
    lines.push('  registry_type:      "insecure"');
    lines.push('  linux_runtime:      "auto"   # auto | docker | podman');
    lines.push('');
    lines.push('# Prereqs (one-time per AWS account):');
    lines.push('#   1. Subscribe to Keysight Marketplace AMIs (KVO, CLMS, vPB)');
    lines.push('#   2. Deploy CLMS via cloudlens-autopilot CFT/Terraform OR manual');
    lines.push('#   3. Get project_key from CLMS UI: Settings > Projects > API Keys');
    lines.push('#   4. Tag target EC2 instances: cloudlens=yes, os=ubuntu|rhel|windows, env=prod');
    return lines.join('\n');
  }

  
  function span(cls, text) {
    var s = document.createElement('span');
    s.className = cls;
    s.textContent = text;
    return s;
  }

  // Tokenize a single .tfvars line into safe DOM nodes (no innerHTML).
  function appendLine(parent, line) {
    // Comment line
    var commentMatch = line.match(/^(\s*)(#.*)$/);
    if (commentMatch) {
      if (commentMatch[1]) parent.appendChild(document.createTextNode(commentMatch[1]));
      parent.appendChild(span('yc', commentMatch[2]));
      return;
    }
    // Terraform key = value pattern
    var keyMatch = line.match(/^(\s*)([a-zA-Z_][\w-]*)(\s*=\s*)(.*)$/);
    var rest = line;
    if (keyMatch) {
      parent.appendChild(document.createTextNode(keyMatch[1]));
      parent.appendChild(span('yk', keyMatch[2]));
      parent.appendChild(document.createTextNode(keyMatch[3]));
      rest = keyMatch[4];
    }
    // Highlight quoted string values
    var re = /"(?:[^"\\]|\\.)*"/g;
    var last = 0;
    var m;
    while ((m = re.exec(rest)) !== null) {
      if (m.index > last) parent.appendChild(document.createTextNode(rest.slice(last, m.index)));
      parent.appendChild(span('yv', m[0]));
      last = m.index + m[0].length;
    }
    if (last < rest.length) parent.appendChild(document.createTextNode(rest.slice(last)));
  }

  function refresh() {
    if (!tfvarsOut) return;
    var t = buildTfvars();
    while (tfvarsOut.firstChild) tfvarsOut.removeChild(tfvarsOut.firstChild);
    var lines = t.split('\n');
    for (var i = 0; i < lines.length; i++) {
      appendLine(tfvarsOut, lines[i]);
      if (i < lines.length - 1) tfvarsOut.appendChild(document.createTextNode('\n'));
    }
  }

  [clmsIp, projKey, tags, rgs, mode].forEach(function (el) {
    if (el) el.addEventListener('input', refresh);
    if (el && el.tagName === 'SELECT') el.addEventListener('change', refresh);
  });

  // password toggle
  var togKey = document.getElementById('toggle-key');
  if (togKey && projKey) {
    togKey.addEventListener('click', function () {
      projKey.type = projKey.type === 'password' ? 'text' : 'password';
    });
  }

  // download — now emits terraform.tfvars
  var dl = document.getElementById('download-yaml'); // keep ID, change behaviour
  if (dl) {
    var dlLabel = dl.querySelector('.label, span');
    if (dlLabel) dlLabel.textContent = 'Download customer_input.yaml';
    dl.addEventListener('click', function () {
      var t = buildTfvars();
      var blob = new Blob([t], { type: 'text/yaml' });
      var url = URL.createObjectURL(blob);
      var a = document.createElement('a');
      a.href = url; a.download = 'customer_input.yaml';
      document.body.appendChild(a); a.click();
      document.body.removeChild(a);
      setTimeout(function () { URL.revokeObjectURL(url); }, 1000);
      flash('Downloaded customer_input.yaml');
    });
  }

  // ----- COPY BUTTONS (data-copy="<id>" -> copies that element's text) -----
  document.querySelectorAll('.copy-btn[data-copy]').forEach(function (btn) {
    btn.addEventListener('click', function () {
      var target = document.getElementById(btn.getAttribute('data-copy'));
      if (!target) return;
      var text = target.innerText || target.textContent || '';
      var done = function () {
        var orig = btn.textContent;
        btn.textContent = 'Copied!';
        btn.classList.add('copied');
        setTimeout(function () {
          btn.textContent = orig;
          btn.classList.remove('copied');
        }, 1600);
      };
      if (navigator.clipboard && navigator.clipboard.writeText) {
        navigator.clipboard.writeText(text).then(done, function () { legacyCopy(text); done(); });
      } else { legacyCopy(text); done(); }
    });
  });

  function legacyCopy(text) {
    var ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed'; ta.style.opacity = '0';
    document.body.appendChild(ta); ta.select();
    try { document.execCommand('copy'); } catch (e) {}
    document.body.removeChild(ta);
  }

  // Hero "Run in CloudShell" — copies the curl command
  var cp = document.getElementById('copy-curl');
  if (cp) {
    cp.addEventListener('click', function () {
      var cmd = 'curl -sSL https://raw.githubusercontent.com/Keysight-Tech/cloudlens-autopilot/main/quickstart.sh | bash';
      if (navigator.clipboard) {
        navigator.clipboard.writeText(cmd).then(function () { flash('Copied curl command to clipboard'); });
      } else { legacyCopy(cmd); flash('Copied curl command'); }
    });
  }

  function flash(msg) {
    var f = document.getElementById('copy-feedback');
    if (!f) return;
    f.textContent = msg;
    setTimeout(function () { f.textContent = ''; }, 2400);
  }

  // ----- SCALING SLIDER (now keyed to E1S/E50 fleet projections) -----
  var slider = document.getElementById('vm-count');
  var vmReadout = document.getElementById('vm-readout');
  var forksReadout = document.getElementById('forks-readout');
  var shardedReadout = document.getElementById('sharded-readout');
  var timeReadout = document.getElementById('time-readout');
  var bars = document.querySelectorAll('.scale-bar');

  function fmt(n) { return n.toLocaleString('en-US'); }

  // Updated bands keyed to AutoPilot's documented sensor deployment scaling
  function bandFor(n) {
    if (n <= 50)     return { time: '5 to 10 min',   forks: 50,   sharded: false, level: 0 };
    if (n <= 200)    return { time: '10 to 20 min',  forks: 100,  sharded: false, level: 1 };
    if (n <= 800)    return { time: '15 to 30 min',  forks: 200,  sharded: false, level: 2 };
    if (n <= 2000)   return { time: '30 to 60 min',  forks: 400,  sharded: true,  level: 3 };
    if (n <= 5000)   return { time: '1 to 2 hours',  forks: 800,  sharded: true,  level: 4 };
    if (n <= 10000)  return { time: '2 to 4 hours',  forks: 1500, sharded: true,  level: 5 };
    return            { time: '4+ hours',           forks: 2500, sharded: true,  level: 6 };
  }

  function updateScaling() {
    if (!slider) return;
    var n = Number(slider.value || 0);
    var b = bandFor(n);
    if (vmReadout) vmReadout.textContent = fmt(n);
    if (forksReadout) forksReadout.textContent = fmt(b.forks);
    if (shardedReadout) shardedReadout.textContent = b.sharded ? 'Yes' : 'No';
    if (timeReadout) timeReadout.textContent = b.time;
    bars.forEach(function (bar) {
      var bl = Number(bar.getAttribute('data-band-level') || 0);
      if (bl <= b.level) bar.classList.add('active');
      else bar.classList.remove('active');
    });
  }
  if (slider) {
    slider.addEventListener('input', updateScaling);
    updateScaling();
  }

  // ----- SMOOTH SCROLL -----
  document.querySelectorAll('a[href^="#"]').forEach(function (a) {
    a.addEventListener('click', function (e) {
      var id = a.getAttribute('href').slice(1);
      var el = document.getElementById(id);
      if (!el) return;
      e.preventDefault();
      el.scrollIntoView({ behavior: 'smooth', block: 'start' });
      if (history.replaceState) history.replaceState(null, '', '#' + id);
    });
  });

  // ----- INITIAL RENDER -----
  refresh();
})();
